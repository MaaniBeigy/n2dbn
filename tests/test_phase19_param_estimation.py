def _chain_posterior(T=4000, A=None, seed=0):
    """
    A hard posterior over a path drawn from the transition matrix `A`.

    `gamma` is one-hot on the sampled path and `xi` is one-hot on consecutive
    pairs, which is the posterior of a chain observed without noise.
    """
    A = np.array([[0.9, 0.1], [0.3, 0.7]]) if A is None else np.asarray(A)
    M = A.shape[0]
    rng = np.random.default_rng(seed)
    path = np.zeros(T, dtype=int)
    for t in range(1, T):
        path[t] = rng.choice(M, p=A[path[t - 1]])

    gamma = np.zeros((T, M))
    gamma[np.arange(T), path] = 1.0
    xi = np.zeros((T - 1, M, M))
    xi[np.arange(T - 1), path[:-1], path[1:]] = 1.0
    return (
        PosteriorSummaries(
            gamma=gamma,
            xi=xi,
            m_H=np.zeros((T, 0)),
            Sigma_H=np.zeros((T, 0, 0)),
            log_Z=0.0,
        ),
        A,
    )


def _regime_params(M=2, d_ctx=0, parent_M=0):
    return RegimeParams(
        M=M,
        parent_M=parent_M,
        d_ctx=d_ctx,
        init=np.zeros(M),
        bias=np.zeros(M),
        trans=np.zeros((M, M)),
        cross=np.zeros((M, parent_M)) if parent_M else None,
        ctx=np.zeros((M, d_ctx)),
    )


