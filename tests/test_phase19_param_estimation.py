def test_the_table_maps_onto_the_transition_logits():
    params = _regime_params()
    init = np.array([0.25, 0.75])
    trans = np.array([[0.9, 0.1], [0.3, 0.7]])
    out = P.regime_params_from_table(params, init, trans)
    assert np.allclose(np.exp(out.init), init)
    assert np.allclose(out.bias, 0.0)
    # trans[m, m_prev] is the log of P(m | m_prev).
    assert out.trans[1, 0] == pytest.approx(np.log(0.1))
    assert out.trans[0, 1] == pytest.approx(np.log(0.3))


def test_a_zero_probability_maps_to_a_finite_logit():
    params = _regime_params()
    out = P.regime_params_from_table(
        params, np.array([1.0, 0.0]), np.array([[1.0, 0.0], [0.0, 1.0]])
    )
    assert np.all(np.isfinite(out.trans))
    assert np.all(np.isfinite(out.init))


def test_the_table_update_reproduces_the_transition_probabilities():
    q, A = _chain_posterior(T=6000)
    out = P.update_regime_table(q, _regime_params(), method="soft-mle")
    probs = np.exp(out.trans)
    assert np.allclose(probs.T, A, atol=0.03)


def test_the_update_leaves_the_context_block_alone():
    q, _ = _chain_posterior(T=500)
    params = _regime_params(d_ctx=2)
    params.ctx = np.array([[0.5, -0.5], [1.0, 2.0]])
    out = P.update_regime_table(q, params)
    assert np.allclose(out.ctx, params.ctx)


