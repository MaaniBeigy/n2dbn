def test_the_table_mode_never_lowers_the_regime_objective():
    from src.learning.mstep import MStep, regime_ll

    q, _ = _chain_posterior(T=800)
    params = _regime_params()
    ctx = np.zeros((q.gamma.shape[0], 0))
    before = regime_ll(q, ctx, params, None)
    step = MStep(regime_update="table+gradient")
    best = max(
        step._regime_candidates(q, ctx, params, None),
        key=lambda c: regime_ll(q, ctx, c, None),
    )
    assert regime_ll(q, ctx, best, None) >= before


def test_the_table_beats_a_bounded_gradient_step_on_a_context_free_chain():
    """With no context the table is the exact maximizer, which gradient is not."""
    from src.learning.mstep import MStep, regime_ll

    q, _ = _chain_posterior(T=2000)
    params = _regime_params()
    ctx = np.zeros((q.gamma.shape[0], 0))
    only_gradient = MStep(regime_update="gradient", n_steps_regime=5)
    only_table = MStep(regime_update="table")
    gradient = only_gradient._regime_candidates(q, ctx, params, None)[0]
    table = only_table._regime_candidates(q, ctx, params, None)[0]
    assert regime_ll(q, ctx, table, None) > regime_ll(q, ctx, gradient, None)
