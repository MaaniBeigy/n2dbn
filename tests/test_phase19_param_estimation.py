"""
Tabular estimation of the regime transition table.

The property that matters is recovery: given a posterior generated by a known
chain, the estimated table has to converge to that chain.  The rest of the file
covers the mapping onto the parameter block, the degenerate posteriors, and the
three modes the parameter step can run the regime block in.
"""

