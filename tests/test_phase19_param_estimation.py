def test_expected_counts_sum_to_the_number_of_transitions():
    q, _ = _chain_posterior(T=500)
    init, trans = P.expected_regime_counts(q)
    assert init.sum() == pytest.approx(1.0)
    assert trans.sum() == pytest.approx(499.0)


def test_expected_counts_of_a_single_epoch_are_all_zero():
    q = PosteriorSummaries(
        gamma=np.array([[0.3, 0.7]]),
        xi=np.zeros((0, 2, 2)),
        m_H=np.zeros((1, 0)),
        Sigma_H=np.zeros((1, 0, 0)),
        log_Z=0.0,
    )
    init, trans = P.expected_regime_counts(q)
    assert np.allclose(init, [0.3, 0.7])
    assert np.allclose(trans, 0.0)


def test_hard_assignment_keeps_every_state_in_the_alphabet():
    q = PosteriorSummaries(
        gamma=np.array([[1.0, 0.0, 0.0]] * 5),
        xi=np.zeros((4, 3, 3)),
        m_H=np.zeros((5, 0)),
        Sigma_H=np.zeros((5, 0, 0)),
        log_Z=0.0,
    )
    frame = P.hard_regime_frame(q)
    assert list(frame.columns) == ["S_prev", "S_t"]
    assert list(frame["S_t"].cat.categories) == [0, 1, 2]


