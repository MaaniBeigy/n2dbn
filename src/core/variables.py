"""
core/variables.py
=================
Container for observed multiscale data and latent-state trajectories.

Key invariant
-------------
For all k in {1,..,K-1}, c in T^(k+1), ℓ in L:
    Σ_{t ∈ child_k(c)}  X_t^(k,ℓ)  =  X_c^(k+1,ℓ)   (RecErr_X = 0)
    Σ_{t ∈ child_k(c)}  Y_t^(k,ℓ)  =  Y_c^(k+1,ℓ)   (RecErr_Y = 0)

This invariant must be checked after generation and (approximately) after inference.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

import numpy as np

from .calendar import SlotCalendar
from .mask import check_ladder, observed_ladder
from .scales import ScaleHierarchy


# ---------------------------------------------------------------------------
@dataclass
class MultiScaleData:
    """
    Observed multiscale arrays for one dataset.

    Storage layout (all lists are length K, index k-1 = scale k):
        X[k-1]  : ndarray  (H_k, L)  int64   - event counts
        Y[k-1]  : ndarray  (H_k, L)  int64   - slot-normalized durations
        C[k-1]  : ndarray  (H_k, d_k) float64 - context features

    `observed` is the provenance of those arrays: one flag per finest slot,
    saying whether the record would have shown a start had one occurred.  It is
    held at the finest scale only, so a coarse mask cannot contradict the fine
    one; `get_observed` derives every coarser one by AND-reduction.  `None`
    means the whole window was watched.

    All indexing is 0-based internally; public methods accept 1-based scales.
    """

    hierarchy: ScaleHierarchy
    label_names: List[str]
    X: List[np.ndarray]  # X[k-1][t, ℓ]
    Y: List[np.ndarray]  # Y[k-1][t, ℓ]
    C: List[np.ndarray]  # C[k-1][t, :]
    calendar: Optional[SlotCalendar] = None
    observed: Optional[np.ndarray] = None  # (H_1,) bool
    _ladder: Optional[List[np.ndarray]] = field(default=None, init=False, repr=False)

    # ------------------------------------------------------------------
    def __post_init__(self) -> None:
        """Check the mask is one boolean flag per finest slot."""
        if self.observed is None:
            return
        self.observed = np.asarray(self.observed)
        if self.observed.dtype != np.bool_:
            raise ValueError(
                f"an observation mask is a boolean array; this one has dtype "
                f"{self.observed.dtype}, which every reader would take for a flag "
                "wherever it is non-zero"
            )
        if self.observed.shape != (self.hierarchy.n_epochs(1),):
            raise ValueError(
                f"an observation mask carries one flag per finest slot, so "
                f"{self.hierarchy.n_epochs(1)} of them; this one carries "
                f"{self.observed.size}"
            )

    # ------------------------------------------------------------------
    @property
    def K(self) -> int:
        return self.hierarchy.K

    @property
    def L(self) -> int:
        return len(self.label_names)

    def get_X(self, k: int) -> np.ndarray:
        """Count array at scale k (1-indexed).  Shape (H_k, L)."""
        return self.X[k - 1]

    def get_Y(self, k: int) -> np.ndarray:
        """Duration array at scale k.  Shape (H_k, L)."""
        return self.Y[k - 1]

    def get_C(self, k: int) -> np.ndarray:
        """Context array at scale k.  Shape (H_k, d_k)."""
        return self.C[k - 1]

    def get_observed(self, k: int = 1) -> np.ndarray:
        """
        Observation flags at scale k, one per epoch, all true when none are held.

        A coarse epoch counts as observed when every finest slot under it is, so
        downstream code reads a flag at whatever scale it works on and never
        branches on the field being absent.
        """
        if self._ladder is None:
            flags = (
                np.ones(self.hierarchy.n_epochs(1), dtype=bool)
                if self.observed is None
                else self.observed
            )
            self._ladder = observed_ladder(flags, self.hierarchy.parent_maps)
        return self._ladder[k - 1]

    # ------------------------------------------------------------------
    # The central correctness check
    # ------------------------------------------------------------------

    def check_reconciliation(self) -> Dict[str, float]:
        """
        Verify exact top-down reconciliation across all scale pairs.

        Returns
        -------
        dict
            `{'RecErr_X': float, 'RecErr_Y': float}`
            Both should equal 0.0 for data generated by the N²DBN.

        Raises
        ------
        ValueError
            When a coarse epoch is only partly observed.  The block sums below
            would still come out at zero there, since they are arithmetic, while
            the coarse total they agree on is a sum over the observed children
            alone.
        """
        if self.observed is not None:
            check_ladder(self.observed, self.hierarchy.parent_maps)

        rec_x = 0.0
        rec_y = 0.0

        for k in range(1, self.K):  # fine scales k = 1..K-1
            X_fine = self.get_X(k)  # (H_k,  L)
            Y_fine = self.get_Y(k)  # (H_k,  L)
            X_par = self.get_X(k + 1)  # (H_{k+1}, L)
            Y_par = self.get_Y(k + 1)  # (H_{k+1}, L)

            H_par = self.hierarchy.n_epochs(k + 1)
            for c in range(H_par):
                ch = self.hierarchy.children(k, c)
                if not ch:
                    continue
                X_sum = X_fine[ch, :].sum(axis=0)  # (L,)
                Y_sum = Y_fine[ch, :].sum(axis=0)  # (L,)
                rec_x += float(np.abs(X_sum - X_par[c]).sum())
                rec_y += float(np.abs(Y_sum - Y_par[c]).sum())

        return {"RecErr_X": rec_x, "RecErr_Y": rec_y}

    # ------------------------------------------------------------------
    # Train / valid / test chronological split
    # ------------------------------------------------------------------

    def split(
        self,
        fracs: Tuple[float, float, float] = (0.7, 0.15, 0.15),
    ) -> Tuple["MultiScaleData", "MultiScaleData", "MultiScaleData"]:
        """
        Chronological split at coarsest-scale boundaries (ensures reconciliation
        is preserved in each subset).

        Returns
        -------
        (train, valid, test) MultiScaleData objects.
        """
        assert abs(sum(fracs) - 1.0) < 1e-6, "fracs must sum to 1"
        H_K = self.hierarchy.n_epochs(self.K)
        if H_K < 3:
            raise ValueError(
                f"cannot split {H_K} coarsest-scale epoch(s) into train/valid/"
                f"test: the scenario needs a deeper coarsest scale (raise "
                f"H_finest or lower the branching factors)"
            )
        n_tr = max(1, round(fracs[0] * H_K))
        n_vl = max(1, round(fracs[1] * H_K))
        n_vl = min(n_vl, H_K - n_tr - 1)
        bounds = [(0, n_tr), (n_tr, n_tr + n_vl), (n_tr + n_vl, H_K)]
        parts = tuple(self._slice_coarse(a, b) for a, b in bounds)
        for name, part, (a, b) in zip(("train", "valid", "test"), parts, bounds):
            if not part.get_observed(1).any():
                raise ValueError(
                    f"the {name} part holds no observed finest slot, so a fit or "
                    f"a score on it is undefined; it covers coarsest epochs "
                    f"{a} to {b - 1} and every slot under them is masked"
                )
        return parts  # type: ignore[return-value]

    def _slice_coarse(self, c_start: int, c_end: int) -> "MultiScaleData":
        """
        Return a MultiScaleData containing only epochs whose coarsest ancestor
        is in [c_start, c_end).
        """
        K = self.K
        hier = self.hierarchy

        # Collect epoch indices at each scale
        idx: List[np.ndarray] = []
        for k in range(1, K + 1):
            ids = np.array(
                [
                    t
                    for t in range(hier.n_epochs(k))
                    if c_start <= hier.ancestor(k, t, K) < c_end
                ],
                dtype=np.int64,
            )
            idx.append(ids)

        # Rebuild parent maps for the slice
        new_H = [len(ids) for ids in idx]
        new_pm: List[Optional[np.ndarray]] = []
        for ki in range(K - 1):
            old_pm = hier.parent_maps[ki]  # (H_{ki+1},)
            old_ids = idx[ki]  # fine indices
            par_ids = idx[ki + 1]  # coarse indices
            # Build reverse lookup: old_coarse_id -> new_coarse_idx
            reverse = {int(old_c): new_c for new_c, old_c in enumerate(par_ids)}
            new_pmap = np.array(
                [reverse[int(old_pm[t])] for t in old_ids], dtype=np.int32
            )
            new_pm.append(new_pmap)
        new_pm.append(None)

        new_hier = ScaleHierarchy(K=K, H=new_H, parent_maps=new_pm)
        new_X = [self.X[k - 1][idx[k - 1]] for k in range(1, K + 1)]
        new_Y = [self.Y[k - 1][idx[k - 1]] for k in range(1, K + 1)]
        new_C = [self.C[k - 1][idx[k - 1]] for k in range(1, K + 1)]
        # The slice starts later in wall-clock time than the full dataset.
        new_cal = (
            self.calendar.shifted(int(idx[0][0]))
            if (self.calendar is not None and len(idx[0]) > 0)
            else self.calendar
        )
        # The slice takes whole coarsest ancestors, so it never cuts a parent
        # block in half and never turns a fully observed coarse epoch into a
        # partly observed one.  That is what lets the mask travel as it is.
        new_obs = None if self.observed is None else self.observed[idx[0]]
        return MultiScaleData(
            hierarchy=new_hier,
            label_names=self.label_names,
            X=new_X,
            Y=new_Y,
            C=new_C,
            calendar=new_cal,
            observed=new_obs,
        )

    # ------------------------------------------------------------------
    @classmethod
    def allocate(
        cls,
        hierarchy: ScaleHierarchy,
        label_names: List[str],
        context_dims: Optional[List[int]] = None,
        calendar: Optional[SlotCalendar] = None,
    ) -> "MultiScaleData":
        """Allocate zero-filled arrays (useful as a pre-allocated buffer)."""
        L = len(label_names)
        K = hierarchy.K
        context_dims = context_dims or [1] * K
        assert len(context_dims) == K

        X = [
            np.zeros((hierarchy.n_epochs(k), L), dtype=np.int64)
            for k in range(1, K + 1)
        ]
        Y = [
            np.zeros((hierarchy.n_epochs(k), L), dtype=np.int64)
            for k in range(1, K + 1)
        ]
        C = [
            np.zeros((hierarchy.n_epochs(k), d), dtype=np.float64)
            for k, d in zip(range(1, K + 1), context_dims)
        ]
        return cls(
            hierarchy=hierarchy,
            label_names=label_names,
            X=X,
            Y=Y,
            C=C,
            calendar=calendar,
        )

    # ------------------------------------------------------------------
    def __repr__(self) -> str:
        lines = [
            f"MultiScaleData  K={self.K}  L={self.L}",
            f"  Labels: {self.label_names}",
        ]
        for k in range(1, self.K + 1):
            x_tot = int(self.get_X(k).sum())
            seen = int(self.get_observed(k).sum())
            lines.append(
                f"  k={k}: H={self.hierarchy.n_epochs(k)}"
                f"  X_sum={x_tot}  observed={seen}"
            )
        return "\n".join(lines)


# ---------------------------------------------------------------------------
@dataclass
class LatentTrajectories:
    """
    Ground-truth (or posterior) latent trajectories used during generation
    and later for evaluation.

    S[k-1][t]      : int   regime label (0-based) at scale k, epoch t
    H_traj[k-1][t] : (r_k,) float  latent factor at scale k, epoch t
    """

    hierarchy: ScaleHierarchy
    S: List[np.ndarray]  # S[k-1] shape (H_k,)  int
    H_traj: List[np.ndarray]  # H_traj[k-1] shape (H_k, r_k)  float

    @property
    def K(self) -> int:
        return self.hierarchy.K

    def get_S(self, k: int) -> np.ndarray:
        """Regime sequence at scale k.  Shape (H_k,)."""
        return self.S[k - 1]

    def get_H(self, k: int) -> np.ndarray:
        """Factor trajectory at scale k.  Shape (H_k, r_k)."""
        return self.H_traj[k - 1]
